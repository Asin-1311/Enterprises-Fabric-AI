"""Prepare the observability profile (M17a): secrets, Langfuse's database and bucket.

    .venv\\Scripts\\python.exe -m scripts.observability_setup            # secrets + database + bucket
    .venv\\Scripts\\python.exe -m scripts.observability_setup --env-only # only the secrets

1. Secrets: every value the profile needs that .env does not have yet is generated at
   random and APPENDED to .env (git-ignored); existing values are never changed. Only the
   names are printed. Needed: LANGFUSE_SALT, LANGFUSE_ENCRYPTION_KEY (64 hex characters),
   LANGFUSE_NEXTAUTH_SECRET, LANGFUSE_PUBLIC_KEY / LANGFUSE_SECRET_KEY (the project keys
   the API sends traces with), LANGFUSE_ADMIN_PASSWORD, CLICKHOUSE_PASSWORD,
   GRAFANA_ADMIN_PASSWORD.
2. Langfuse's own PostgreSQL database `langfuse` (in the existing server), if missing.
3. Langfuse's own MinIO bucket `langfuse`, if missing.
Steps 2 and 3 need PostgreSQL and MinIO running (`--profile observability up -d` starts
them; Langfuse restarts by itself until both exist).
"""

import argparse
import secrets
import sys

from app.config import PROJECT_ROOT

ENV_FILE = PROJECT_ROOT / ".env"
GENERATED = {
    "LANGFUSE_SALT": lambda: secrets.token_urlsafe(32),
    "LANGFUSE_ENCRYPTION_KEY": lambda: secrets.token_hex(32),
    "LANGFUSE_NEXTAUTH_SECRET": lambda: secrets.token_urlsafe(32),
    "LANGFUSE_PUBLIC_KEY": lambda: f"pk-lf-{secrets.token_hex(16)}",
    "LANGFUSE_SECRET_KEY": lambda: f"sk-lf-{secrets.token_hex(16)}",
    "LANGFUSE_ADMIN_PASSWORD": lambda: secrets.token_urlsafe(18),
    "CLICKHOUSE_PASSWORD": lambda: secrets.token_urlsafe(24),
    "GRAFANA_ADMIN_PASSWORD": lambda: secrets.token_urlsafe(18),
}


def existing_names(text: str) -> set[str]:
    return {line.split("=", 1)[0].strip() for line in text.splitlines()
            if "=" in line and not line.lstrip().startswith("#")}


def ensure_secrets(env_file=ENV_FILE) -> list[str]:
    """Append the missing secrets to .env; returns the names added."""
    text = env_file.read_text(encoding="utf-8") if env_file.exists() else ""
    missing = [name for name in GENERATED if name not in existing_names(text)]
    if missing:
        lines = ["", "# Observability profile (M17a): generated by scripts/observability_setup.py"]
        lines += [f"{name}={GENERATED[name]()}" for name in missing]
        with env_file.open("a", encoding="utf-8") as f:
            f.write(("\n" if text and not text.endswith("\n") else "") + "\n".join(lines) + "\n")
    return missing


def ensure_database(settings) -> str:
    import psycopg
    from sqlalchemy.engine import make_url

    url = make_url(settings.database_url)
    with psycopg.connect(host=url.host, port=url.port or 5432, user=url.username,
                         password=url.password, dbname=url.database, autocommit=True) as conn:
        if conn.execute("SELECT 1 FROM pg_database WHERE datname = 'langfuse'").fetchone():
            return "database langfuse exists"
        conn.execute("CREATE DATABASE langfuse")
        return "database langfuse created"


def ensure_bucket() -> str:
    import boto3
    from botocore.exceptions import ClientError

    from app.config import env_reference

    s3 = boto3.client("s3", endpoint_url="http://127.0.0.1:9000", region_name="us-east-1",
                      aws_access_key_id=env_reference("env:MINIO_ROOT_USER"),
                      aws_secret_access_key=env_reference("env:MINIO_ROOT_PASSWORD"))
    try:
        s3.head_bucket(Bucket="langfuse")
        return "bucket langfuse exists"
    except ClientError:
        s3.create_bucket(Bucket="langfuse")
        return "bucket langfuse created"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Prepare the observability profile.")
    parser.add_argument("--env-only", action="store_true", help="only add the missing secrets to .env")
    args = parser.parse_args(argv)
    added = ensure_secrets()
    print(f"Secrets added to .env: {', '.join(added) if added else 'none (all present)'}.")
    if args.env_only:
        return 0
    from app.config import get_settings

    settings = get_settings()
    if not settings.database_url:
        print("DATABASE_URL is not set in .env: cannot create Langfuse's database.")
        return 1
    print(ensure_database(settings))
    print(ensure_bucket())
    return 0


if __name__ == "__main__":
    sys.exit(main())
